/**
 * Licences whose data may be baked into a shipped world. Everything else is
 * reference-only: an agent may look at it to decide a number, but the bytes must
 * not land in the repo. Google Earth / Street View sit in that second bucket, which
 * is exactly the constraint union-square-sf/PROMPT.md states in prose.
 */
export const REDISTRIBUTABLE = Object.entries(LICENSES)
  .filter(([, l]) => l.redistributable)
  .map(([id]) => id);

export function assertKnownLicense(id) {
  if (!LICENSES[id]) {
    throw new Error(
      `unknown license id "${id}". Add it to ingest/src/licenses.mjs with an explicit ` +
        'redistributable flag before any adapter claims it.',
    );
  }
  return LICENSES[id];
}

/** Render the ATTRIBUTION.md that every world ships if it uses attributed sources. */
export function renderAttribution(worldId, usedSources) {
  const lines = [
    `# Data attribution — ${worldId}`,
    '',
    `GENERATED by \`node ingest/bin/ingest.mjs build ${worldId}\`. Do not edit by hand.`,
    '',
    'This world is assembled from the public datasets below. Each entry is the licence',
    'the upstream publisher actually applies; the derived database in this repository',
    'inherits the most restrictive of them.',
    '',
    '| Source | Dataset | Licence | Attribution |',
    '|---|---|---|---|',
  ];
  for (const s of usedSources) {
    const lic = LICENSES[s.license];
    const licCell = lic?.url ? `[${lic.name}](${lic.url})` : (lic?.name ?? s.license);
    lines.push(`| \`${s.id}\` | ${s.title} | ${licCell} | ${s.attribution} |`);
  }
  const shareAlike = usedSources.filter((s) => LICENSES[s.license]?.class === 'share-alike');
  if (shareAlike.length) {
    lines.push(
      '',
      '## Share-alike notice',
      '',
      'The sources below are share-alike. The **derived database** in this world',
      '(footprints, street centrelines, elevations, place records) is therefore itself',
      'share-alike; the rendering code around it remains MIT.',
      '',
      ...shareAlike.map((s) => `- ${s.attribution} — ${LICENSES[s.license].name}`),
    );
  }
  const restricted = usedSources.filter((s) => LICENSES[s.license]?.class === 'restricted');
  if (restricted.length) {
    lines.push(
      '',
      '## Reference-only sources',
      '',
      'Consulted during reconstruction. No bytes from these sources are redistributed here;',
      'they informed measurements that were then reproduced procedurally.',
      '',
      ...restricted.map((s) => `- ${s.title} — ${s.attribution}`),
    );
  }
  return lines.join('\n') + '\n';
}
