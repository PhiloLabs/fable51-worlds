/**
 * licenses.mjs — what each upstream dataset actually permits, and what that means
 * for a repo whose own code is MIT.
 *
 * The root README already says the right thing in prose ("Geometry is derived from
 * OpenStreetMap (ODbL) and USGS 3DEP (public domain)"). This turns that prose into
 * a gate: every ingested feature carries the id of the source it came from, and
 * `ingest verify` fails if a feature's licence is unknown, if a non-redistributable
 * source contributed shipped bytes, or if a required attribution never reaches the
 * generated ATTRIBUTION.md.
 *
 * The distinction that matters is SHARE-ALIKE vs PERMISSIVE. ODbL share-alike runs
 * with the *database*, not with the rendering code, which is why the runtime ships
 * under MIT while the derived database stays ODbL — but only as long as the
 * attribution actually ships. Hence `requiresAttribution`.
 */

